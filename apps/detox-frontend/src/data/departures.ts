export function getDeparturesByPackageSlug(packageSlug: string): Departure[] {
  return departures.filter((d) => d.packageSlug === packageSlug);
}

export function getDepartureByCode(code: string): Departure | undefined {
  return departures.find((d) => d.code === code);
}

export function getUpcomingDepartures(limit = 6): Departure[] {
  const today = new Date().toISOString().split("T")[0];
  return departures
    .filter((d) => d.startDate >= today && d.status !== "closed")
    .sort((a, b) => a.startDate.localeCompare(b.startDate))
    .slice(0, limit);
}
