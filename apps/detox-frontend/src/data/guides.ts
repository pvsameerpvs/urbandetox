export function getGuideBySlug(slug: string) {
  return guides.find((g) => g.slug === slug);
}

export function getFeaturedGuides(limit = 4) {
  return guides.filter((g) => g.featured).slice(0, limit);
}

export function getAllGuides() {
  return guides;
}

export function getGuidesByCategory(category: string) {
  return guides.filter((g) => g.category === category);
}

export function getGuideCategories() {
  return Array.from(new Set(guides.map((g) => g.category)));
}

export function getRelatedGuides(currentSlug: string, limit = 3) {
  const current = getGuideBySlug(currentSlug);
  if (!current) return [];
  return guides
    .filter(
      (g) =>
        g.slug !== currentSlug &&
        (g.destinationSlug === current.destinationSlug ||
          g.category === current.category)
    )
    .slice(0, limit);
}
